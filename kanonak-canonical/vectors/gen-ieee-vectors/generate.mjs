// The IEEE carriers' cases, derived rather than hand-typed. `canonical-form` writes a double as the shortest
// round-tripping decimal in RFC 8785's notation, and RFC 8785 defines that notation as ECMAScript's
// Number::toString, so this engine's own String(n) is the definition, not a port. A float is its value rounded to
// 32 bits, then written as that double (runtime#35).
//
// `node generate.mjs` writes ../lexical-ieee-vectors.json; `node generate.mjs --check` fails if it would change it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../lexical-ieee-vectors.json', import.meta.url));

// Each input is here for a reason: a point where some language's own formatter changes notation or digits, so a
// port that leans on it shows up. Every port must give the ECMAScript answer at every one of them.
const doubles = {
  'ecmascript-band-low-outside': ['1e-7', '9.99999999999999e-7', '-1e-7'],
  'ecmascript-band-low-inside': ['1e-6', '1.5e-6', '-0.000001'],
  'ecmascript-band-high-inside': ['1e20', '9.99999999999999e20', '123456789012345678901'],
  'ecmascript-band-high-outside': ['1e21', '1.5e21', '-1e21', '1E21', '1e+21'],
  'python-repr-switch': ['0.0001', '0.00001', '9999999999999998', '1e16'],
  'go-g-switch': ['999999', '1000000', '1234567', '0.00001234'],
  'java-tostring-switch': ['0.001', '0.0009', '9999999', '10000000'],
  'dotnet-tostring-switch': ['123456789012345', '1e15', '1e-5'],
  'rust-display-never-exponent': ['1e300', '5e-324', '1.7976931348623157e308', '2.2250738585072014e-308'],
  'shortest-digits': ['0.1', '0.30000000000000004', '0.3333333333333333', '123.456', '9007199254740992', '9007199254740993'],
  'lexical-shapes': ['.5', '5.', '+1.5', '1.50e+2'],
  'out-of-range': ['1e400', '-1e400'],
};

const floats = {
  'widened-not-float-shortest': ['1.1', '0.1', '3.14159'],
  'rounds-to-32-bits': ['16777217', '0.333333333333'],
  'float-extremes': ['3.4028234663852886e38', '1.17549435e-38', '1.401298464324817e-45'],
  'underflow-to-zero': ['1e-46'],
  'out-of-range': ['3.5e38', '1e39'],
};

function expectedOf(carrier, input) {
  const n = carrier === 'float' ? Math.fround(Number(input)) : Number(input);
  if (!Number.isFinite(n)) return { expectError: true };
  return { expected: n === 0 ? '0' : String(n) };
}

const slug = (s) => s.replace(/^\+/, 'plus-').replace(/^-/, 'minus-').replace(/^\./, 'point-').replace(/[^0-9A-Za-z]+/g, '_');

const vectors = [];
for (const [carrier, groups] of [['double', doubles], ['float', floats]]) {
  for (const [why, inputs] of Object.entries(groups)) {
    for (const input of inputs) {
      vectors.push({ id: `${carrier}-${why}-${slug(input)}`, carrier, input, ...expectedOf(carrier, input) });
    }
  }
}

const ids = new Set();
for (const v of vectors) {
  if (ids.has(v.id)) throw new Error(`two cases are named ${v.id}: make the input's slug distinct`);
  ids.add(v.id);
}

const doc = {
  canonicalFormVersion: '1',
  description:
    'Generated by gen-ieee-vectors/generate.mjs: never edit by hand. The xsd:double and xsd:float carriers at the ' +
    'points where language formatters disagree. Expected values are ECMAScript Number::toString, which RFC 8785 ' +
    'names as the number serialization; a float is first rounded to 32 bits. Same shape as lexical-vectors.json.',
  vectors,
};
const text = JSON.stringify(doc, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`${OUT} is not what gen-ieee-vectors/generate.mjs makes. Run: node kanonak-canonical/vectors/gen-ieee-vectors/generate.mjs`);
    process.exit(1);
  }
  console.log(`lexical-ieee-vectors.json: ${vectors.length} cases, as generated`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${vectors.length} cases to ${OUT}`);
}
